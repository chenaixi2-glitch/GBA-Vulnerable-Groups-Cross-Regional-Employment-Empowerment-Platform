// zh-TW: derive from zh-CN with common character swaps + explicit overrides
function toTraditional(obj) {
  if (typeof obj === 'string') {
    return obj
      .replace(/语言/g, '語言')
      .replace(/登录/g, '登入')
      .replace(/注册/g, '註冊')
      .replace(/简历/g, '履歷')
      .replace(/岗位/g, '崗位')
      .replace(/加载/g, '載入')
      .replace(/保存/g, '保存')
      .replace(/失败/g, '失敗')
      .replace(/请/g, '請')
      .replace(/确认/g, '確認')
      .replace(/上传/g, '上傳')
      .replace(/导出/g, '匯出')
      .replace(/网络/g, '網路')
      .replace(/后端/g, '後端')
      .replace(/服务器/g, '伺服器')
      .replace(/会话/g, '工作階段')
      .replace(/模拟/g, '模擬')
      .replace(/面试/g, '面試')
      .replace(/学习/g, '學習')
      .replace(/路径/g, '路徑')
      .replace(/资料/g, '資料')
      .replace(/个人/g, '個人')
      .replace(/企业/g, '企業')
      .replace(/账户/g, '帳戶')
      .replace(/网站/g, '網站')
      .replace(/简体/g, '簡體')
      .replace(/繁体/g, '繁體')
      .replace(/葡语/g, '葡語')
      .replace(/残疾/g, '殘疾')
      .replace(/弱势/g, '弱勢')
      .replace(/群体/g, '群體')
      .replace(/捐赠/g, '捐贈')
      .replace(/爱心/g, '愛心');
  }
  if (Array.isArray(obj)) return obj.map(toTraditional);
  if (obj && typeof obj === 'object') {
    const out = {};
    Object.keys(obj).forEach((k) => { out[k] = toTraditional(obj[k]); });
    return out;
  }
  return obj;
}

