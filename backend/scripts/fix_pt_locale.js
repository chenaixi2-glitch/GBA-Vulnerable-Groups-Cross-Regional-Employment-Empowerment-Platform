function countCn(obj, prefix) {
  if (typeof obj === 'string') {
    if (cn.test(obj)) {
      remaining++;
      if (remaining <= 5) console.warn('still CN:', prefix, obj.slice(0, 50));
    }
    return;
  }
  if (obj && typeof obj === 'object') {
    Object.keys(obj).forEach((k) => countCn(obj[k], prefix ? prefix + '.' + k : k));
  }
}
