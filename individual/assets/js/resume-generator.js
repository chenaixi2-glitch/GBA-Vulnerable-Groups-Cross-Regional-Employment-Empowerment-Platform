async function proceedToJdStep() {
    if (typeof refreshAndValidateRequiredFields !== 'function') {
        revealJdSection();
        document.getElementById('jd-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
        return;
    }

    try {
        Utils.showLoading(uiT('resume.toast.validatingProfile', 'Checking required profile fields...'));
        const { valid, required } = await refreshAndValidateRequiredFields();
        Utils.hideLoading();

        if (!valid && required.length) {
            const labels = required.slice(0, 5).map((item) => item.label).join(', ');
            Utils.showToast(uiT('resume.toast.requiredFieldsMissing', 'Please complete required fields first: {labels}', { labels }));
            if (typeof scrollToChecklistField === 'function') {
                scrollToChecklistField(required[0]);
            }
            return;
        }

        revealJdSection();
        Utils.showToast(uiT('resume.toast.profileReadyForStep2', 'Profile complete — continue with your target job description'));
        document.getElementById('jd-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast(uiT('resume.toast.validateProfileFailed', 'Could not validate profile: {msg}', { msg: error.message }));
    }
}

