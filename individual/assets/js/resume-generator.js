/**
 * GBA Platform - Resume Generator
 */

let currentFile = null;
let resumeGenerated = false;
let jdAutoGenerated = false;
let jdUserConfirmed = false;
let currentResumeLanguage = 'zh';
let pendingExportFormat = null;

const INDUSTRY_LABELS = {
    tech: 'Technology',
    finance: 'Finance',
    ecommerce: 'E-commerce',
    healthcare: 'Healthcare',
    education: 'Education',
    other: 'Other',
};

const EMPLOYER_TYPE_LABELS = {
    soe: 'State-owned Enterprise (国央企)',
    public: 'Public Sector (体制内)',
    foreign: 'Foreign Enterprise (外企)',
    private: 'Private Enterprise (民企)',
    npo: 'Non-profit Organization (NPO/NGO 非营利社会组织)',
    hmt: 'HK/Macau/TW-funded Enterprise (港澳台资企业)',
    other: 'Other (其他)',
};

const EXPERIENCE_LABELS = {
    entry: 'Entry Level (0-2 years)',
    mid: 'Mid Level (3-5 years)',
    senior: 'Senior Level (5+ years)',
    executive: 'Executive / Leadership',
};

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
    initializeResumeGenerator();
});

function initializeResumeGenerator() {
    // Load session
    const sessionId = apiClient.loadSessionId();
    if (sessionId) {
        Utils.updateSessionDisplay(sessionId);
    } else {
        apiClient.generateSessionId();
        Utils.updateSessionDisplay(apiClient.sessionId);
    }

    // Setup file drag and drop
    setupDragAndDrop();
    setupJdSectionListeners();
    setupExportModal();
    restoreDraftOnLoad();
}

async function restoreDraftOnLoad() {
    try {
        const restored = await ProfileEditor.loadFromServer();
        if (restored) {
            document.getElementById('jd-section')?.classList.remove('hidden');
            updateStepIndicator(1, 'completed');
            updateStepIndicator(2, 'active');
        }
    } catch (_) {
        /* no draft yet */
    }
}

function setupExportModal() {
    document.getElementById('btn-save-and-export')?.addEventListener('click', async () => {
        hideSaveModal();
        try {
            Utils.showLoading('Saving to your account...');
            await apiClient.saveResumeToAccount();
            Utils.hideLoading();
            Utils.showToast('Resume saved to your account');
        } catch (error) {
            Utils.hideLoading();
            Utils.showToast('Save failed: ' + error.message);
            return;
        }
        await runPendingExport();
    });

    document.getElementById('btn-export-only')?.addEventListener('click', async () => {
        hideSaveModal();
        await runPendingExport();
    });

    document.getElementById('btn-cancel-export')?.addEventListener('click', () => {
        pendingExportFormat = null;
        hideSaveModal();
    });
}

function showSaveModal() {
    document.getElementById('save-resume-modal')?.classList.remove('hidden');
}

function hideSaveModal() {
    document.getElementById('save-resume-modal')?.classList.add('hidden');
}

async function promptExportResume(format) {
    pendingExportFormat = format;
    if (apiClient.isLoggedIn() && resumeGenerated) {
        showSaveModal();
        return;
    }
    await runPendingExport();
}

async function runPendingExport() {
    const format = pendingExportFormat;
    pendingExportFormat = null;
    if (!format) return;

    if (format === 'html') {
        await downloadResume('html');
    } else {
        await exportResume(format);
    }
}

async function syncDraftBeforeGenerate() {
    if (typeof ProfileEditor !== 'undefined' && ProfileEditor.collectDraftFromForm) {
        const draft = ProfileEditor.collectDraftFromForm();
        ProfileEditor.draft = draft;
        await apiClient.saveResumeDraft(draft);
    }
}

function setupJdSectionListeners() {
    const industrySelect = document.getElementById('industry-select');
    const experienceSelect = document.getElementById('experience-level');
    const employerTypeSelect = document.getElementById('employer-type-select');
    const jdTextarea = document.getElementById('jd-text');

    if (!industrySelect || !experienceSelect) return;

    const maybeAutoGenerateJd = Utils.debounce(async () => {
        if (jdTextarea.value.trim() || jdAutoGenerated) return;
        const industry = industrySelect.value;
        const experienceLevel = experienceSelect.value;
        const employerType = employerTypeSelect?.value || '';
        if (!industry || !experienceLevel || !employerType) return;
        await fillSuggestedJd(industry, experienceLevel, employerType, { silent: true });
    }, 800);

    industrySelect.addEventListener('change', maybeAutoGenerateJd);
    experienceSelect.addEventListener('change', maybeAutoGenerateJd);
    employerTypeSelect?.addEventListener('change', async () => {
        const employerType = employerTypeSelect.value;
        if (employerType) {
            await onEmployerTypeSelected(employerType);
        }
        maybeAutoGenerateJd();
    });

    jdTextarea.addEventListener('input', () => {
        if (jdTextarea.value.trim()) {
            jdAutoGenerated = false;
            jdUserConfirmed = false;
        }
    });
}

function getIndustryLabel(value) {
    return INDUSTRY_LABELS[value] || value;
}

function getExperienceLabel(value) {
    return EXPERIENCE_LABELS[value] || value;
}

function getEmployerTypeLabel(value) {
    return EMPLOYER_TYPE_LABELS[value] || value;
}

/**
 * Generate and fill suggested JD from industry, employer type, experience level, and uploaded resume
 */
async function fillSuggestedJd(industry, experienceLevel, employerType, options = {}) {
    const { silent = false } = options;
    const jdTextarea = document.getElementById('jd-text');
    const generateBtn = document.getElementById('btn-generate-jd');

    try {
        if (generateBtn) generateBtn.disabled = true;
        if (!silent) {
            Utils.showLoading('Generating suggested job description...');
        }

        const result = await apiClient.generateJobDescription(
            getIndustryLabel(industry),
            getExperienceLabel(experienceLevel),
            employerType
        );

        if (result.jd_text) {
            jdTextarea.value = result.jd_text;
            jdAutoGenerated = true;
            jdUserConfirmed = false;
            document.getElementById('jd-generated-hint')?.classList.remove('hidden');
            if (!silent) {
                const cacheMsg = result.from_cache
                    ? 'Loaded suggested job description from cache — you can edit it before continuing'
                    : 'Suggested job description generated — you can edit it before continuing';
                Utils.showToast(cacheMsg);
            }
        }
    } catch (error) {
        if (!silent) {
            Utils.showToast('Failed to generate job description: ' + error.message);
        }
        console.error('JD generation error:', error);
    } finally {
        if (generateBtn) generateBtn.disabled = false;
        if (!silent) {
            Utils.hideLoading();
        }
    }
}

async function generateSuggestedJd() {
    const industry = document.getElementById('industry-select').value;
    const experienceLevel = document.getElementById('experience-level').value;
    const employerType = document.getElementById('employer-type-select')?.value || '';

    if (!industry || !experienceLevel || !employerType) {
        Utils.showToast('Please select industry, employer type, and experience level first');
        return;
    }

    await fillSuggestedJd(industry, experienceLevel, employerType, { silent: false });
}

/**
 * Setup drag and drop for file upload
 */
function setupDragAndDrop() {
    const dropZone = document.querySelector('.border-dashed');
    
    ['dragenter', 'dragover', 'dragleave', 'drop'].forEach(eventName => {
        dropZone.addEventListener(eventName, preventDefaults, false);
    });

    function preventDefaults(e) {
        e.preventDefault();
        e.stopPropagation();
    }

    ['dragenter', 'dragover'].forEach(eventName => {
        dropZone.addEventListener(eventName, () => {
            dropZone.classList.add('border-blue-500', 'bg-blue-50');
        });
    });

    ['dragleave', 'drop'].forEach(eventName => {
        dropZone.addEventListener(eventName, () => {
            dropZone.classList.remove('border-blue-500', 'bg-blue-50');
        });
    });

    dropZone.addEventListener('drop', (e) => {
        const files = e.dataTransfer.files;
        if (files.length > 0) {
            handleFile(files[0]);
        }
    });
}

/**
 * Handle file selection
 */
function handleFileSelect(event) {
    const file = event.target.files[0];
    if (file) {
        handleFile(file);
    }
}

/**
 * Process selected file
 */
function handleFile(file) {
    // Validate file type
    const validTypes = ['.pdf', '.docx', '.txt', '.md'];
    const fileExtension = '.' + file.name.split('.').pop().toLowerCase();
    
    if (!validTypes.includes(fileExtension)) {
        Utils.showToast('不支持的文件格式，请上传 PDF、DOCX、TXT 或 MD');
        return;
    }

    // Validate file size (10MB max)
    if (file.size > 10 * 1024 * 1024) {
        Utils.showToast('File too large. Maximum size is 10MB');
        return;
    }

    currentFile = file;

    // Display file info
    document.getElementById('file-name').textContent = file.name;
    document.getElementById('file-size').textContent = Utils.formatFileSize(file.size);
    document.getElementById('file-info').classList.remove('hidden');

    // Enable continue button
    document.getElementById('btn-upload-resume').disabled = false;

    Utils.showToast('File uploaded successfully');
}

/**
 * Clear selected file
 */
function clearFile() {
    currentFile = null;
    document.getElementById('resume-file').value = '';
    document.getElementById('file-info').classList.add('hidden');
    document.getElementById('btn-upload-resume').disabled = true;
}

/**
 * Upload resume and trigger profile_agent
 */
async function uploadResume() {
    const resumeText = document.getElementById('resume-text').value.trim();

    if (!currentFile && !resumeText) {
        Utils.showToast('Please upload a file or paste resume text');
        return;
    }

    try {
        Utils.showLoading('Uploading resume...');
        updateStepIndicator(1, 'completed');

        let response;
        
        if (currentFile) {
            // Upload file
            response = await apiClient.uploadResume(currentFile);
        } else {
            // Use pasted text
            response = await apiClient.chat(resumeText, []);
        }

        Utils.hideLoading();
        Utils.showToast('Resume analyzed successfully');

        await ProfileEditor.initFromUpload(response);

        // Scroll to profile editor
        document.getElementById('profile-editor-section')?.scrollIntoView({ behavior: 'smooth' });

        console.log('Profile agent response:', response);
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast('Failed to upload resume: ' + error.message);
        console.error('Upload error:', error);
    }
}

/**
 * Generate customized resume
 */
async function generateResume() {
    let jdText = document.getElementById('jd-text').value.trim();
    const industry = document.getElementById('industry-select').value;
    const experienceLevel = document.getElementById('experience-level').value;
    const employerType = document.getElementById('employer-type-select')?.value || '';

    if (!jdText) {
        if (!industry || !experienceLevel || !employerType) {
            Utils.showToast('Paste a job description, or select industry, employer type, and experience level to generate one');
            return;
        }
        await fillSuggestedJd(industry, experienceLevel, employerType, { silent: false });
        jdText = document.getElementById('jd-text').value.trim();
        if (!jdText) {
            Utils.showToast('Could not generate job description. Please try again or paste one manually');
            return;
        }
    }

    // 岗位名 / 自动生成 JD 须用户确认后再进入优化
    let jdAlignmentHint = '';
    const confirmResult = await ensureJdConfirmedBeforeProceed(jdText, {
        jdAutoGenerated,
        jdUserConfirmed,
    });
    if (!confirmResult?.confirmed) {
        Utils.showToast('已取消，请确认岗位描述后再生成简历');
        return;
    }
    jdText = confirmResult.jd_text || document.getElementById('jd-text').value.trim();
    jdUserConfirmed = true;
    jdAutoGenerated = false;
    jdAlignmentHint = confirmResult.clarification_hint || confirmResult.alignment_note || '';

    try {
        await syncDraftBeforeGenerate();

        Utils.showLoading('Analyzing job description...');
        document.getElementById('agent-status-panel').classList.remove('hidden');
        document.getElementById('empty-state').classList.add('hidden');

        updateStepIndicator(2, 'completed');
        updateStepIndicator(3, 'active');

        updateAgentStatus('agent-profile', 'completed');
        updateAgentStatus('agent-jd', 'running');

        const targetContext = typeof collectTargetJobContext === 'function' ? collectTargetJobContext() : null;

        const jdResponse = await apiClient.submitJobDescription(jdText, targetContext);

        updateAgentStatus('agent-jd', 'completed');
        updateAgentStatus('agent-gap', 'running');

        if (jdResponse.gaps && jdResponse.gaps.length > 0) {
            displayGapAnalysis(jdResponse.gaps);
        }

        updateAgentStatus('agent-gap', 'completed');
        Utils.hideLoading();

        // 交互式追问：技术栈/经历不明确时向用户提问
        const optimizationResult = await showOptimizationDialog({
            gaps: jdResponse.gaps || [],
            questions: jdResponse.questions_to_ask || [],
            alignmentHint: jdAlignmentHint,
        });
        if (!optimizationResult?.proceed) {
            Utils.showToast('已取消简历生成');
            return;
        }

        const answered = (optimizationResult.answers || []).filter((a) => a.answer);
        if (answered.length) {
            Utils.showLoading('Updating profile with your answers...');
            await apiClient.submitOptimizationClarifications(answered);
            Utils.hideLoading();
        }

        updateAgentStatus('agent-content', 'running');
        Utils.showLoading('Generating your customized resume...');

        const resumeResponse = await apiClient.generateResume(
            'Please generate a customized resume based on my experience and target position. Keep all content within one A4 page.',
            targetContext
        );

        updateAgentStatus('agent-content', 'completed');
        updateAgentStatus('agent-render', 'running');

        if (resumeResponse.resume_html && resumeResponse.resume_html.html) {
            displayResume(resumeResponse.resume_html.html);
            updateResumeLanguageBadge(resumeResponse.resume_content_json?.meta?.language || 'zh');
        } else {
            const resumeData = await apiClient.getResumeHtml();
            if (resumeData.resume_html && resumeData.resume_html.html) {
                displayResume(resumeData.resume_html.html);
                updateResumeLanguageBadge('zh');
            } else {
                throw new Error('Resume HTML not available');
            }
        }

        updateAgentStatus('agent-render', 'completed');
        Utils.hideLoading();

        document.getElementById('resume-preview-section').classList.remove('hidden');
        document.getElementById('gap-analysis-section').classList.remove('hidden');

        updateStepIndicator(3, 'completed');
        resumeGenerated = true;

        await refreshLanguageChecklist(currentResumeLanguage);

        Utils.showToast('Resume generated successfully!');

        document.getElementById('resume-preview-section').scrollIntoView({ behavior: 'smooth' });

        console.log('Resume generation complete:', resumeResponse);
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast('Failed to generate resume: ' + error.message);
        console.error('Generation error:', error);

        updateAgentStatus('agent-jd', 'failed');
        updateAgentStatus('agent-gap', 'failed');
        updateAgentStatus('agent-content', 'failed');
        updateAgentStatus('agent-render', 'failed');
    }
}

/**
 * Display gap analysis results
 */
function displayGapAnalysis(gaps) {
    const container = document.getElementById('gap-analysis-content');
    
    if (!gaps || gaps.length === 0) {
        container.innerHTML = '<p class="text-gray-600">No significant skill gaps detected!</p>';
        return;
    }

    const html = gaps.map(gap => `
        <div class="gap-analysis-card">
            <div class="flex items-start justify-between mb-2">
                <div>
                    <h4 class="font-bold text-gray-900">${gap.skill || gap.description}</h4>
                    <p class="text-sm text-gray-600 mt-1">${gap.suggestion || 'Consider developing this skill'}</p>
                </div>
                <span class="px-3 py-1 rounded-full text-xs font-medium ${getSeverityClass(gap.severity)}">
                    ${gap.severity || 'Medium'} Priority
                </span>
            </div>
            ${gap.type ? `<div class="text-xs text-gray-500">Type: ${gap.type}</div>` : ''}
        </div>
    `).join('');

    container.innerHTML = html;
}

/**
 * Get CSS class based on severity
 */
function getSeverityClass(severity) {
    switch (severity?.toLowerCase()) {
        case 'high':
        case 'critical':
            return 'bg-red-100 text-red-800';
        case 'medium':
            return 'bg-yellow-100 text-yellow-800';
        case 'low':
            return 'bg-green-100 text-green-800';
        default:
            return 'bg-gray-100 text-gray-800';
    }
}

/**
 * Display generated resume
 */
function displayResume(htmlContent) {
    const previewContainer = document.getElementById('resume-preview');
    previewContainer.innerHTML = htmlContent;
}

/**
 * Update language badge and toggle button states
 */
function updateResumeLanguageBadge(language) {
    currentResumeLanguage = (language || 'zh').toLowerCase().startsWith('en') ? 'en' : 'zh';
    const badge = document.getElementById('resume-language-badge');
    const a4Badge = document.getElementById('resume-a4-badge');
    const btnToEn = document.getElementById('btn-translate-en');
    const btnToZh = document.getElementById('btn-translate-zh');

    if (badge) {
        badge.textContent = currentResumeLanguage === 'en' ? 'English' : '中文';
        badge.className = currentResumeLanguage === 'en'
            ? 'px-2 py-0.5 rounded text-xs font-medium bg-blue-100 text-blue-800'
            : 'px-2 py-0.5 rounded text-xs font-medium bg-red-100 text-red-800';
    }
    if (a4Badge) {
        a4Badge.classList.remove('hidden');
    }
    if (btnToEn) btnToEn.disabled = currentResumeLanguage === 'en';
    if (btnToZh) btnToZh.disabled = currentResumeLanguage === 'zh';

    if (resumeGenerated) {
        refreshLanguageChecklist(currentResumeLanguage);
    }
}

/**
 * Convert resume to English
 */
async function translateResumeToEnglish() {
    if (!resumeGenerated) {
        await onResumeLanguageSelected('en');
        return;
    }
    await translateResume('en');
}

/**
 * Convert resume to Chinese
 */
async function translateResumeToChinese() {
    if (!resumeGenerated) {
        await onResumeLanguageSelected('zh');
        return;
    }
    await translateResume('zh');
}

/**
 * Shared translate handler
 */
async function translateResume(targetLanguage) {
    try {
        Utils.showLoading(targetLanguage === 'en' ? 'Converting to English resume...' : '正在转换为中文简历...');
        const response = await apiClient.translateResume(targetLanguage);

        if (response.resume_html && response.resume_html.html) {
            displayResume(response.resume_html.html);
        }
        updateResumeLanguageBadge(response.language || targetLanguage);
        if (response.language_checklist) {
            renderLanguageChecklistPanel(response.language_checklist);
        } else {
            await refreshLanguageChecklist(targetLanguage);
        }
        Utils.hideLoading();
        const missing = response.language_checklist?.missing_count || 0;
        const baseMsg = targetLanguage === 'en'
            ? 'Resume converted to English (A4 single page)'
            : '已转换为中文简历（A4 单页）';
        Utils.showToast(missing > 0 ? `${baseMsg} — ${missing} item(s) to review below` : baseMsg);
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast('Translation failed: ' + error.message);
        console.error('Translation error:', error);
    }
}

/**
 * Optimize resume content (A4 one-page)
 */
async function optimizeResume() {
    if (!resumeGenerated) {
        Utils.showToast('Please generate a resume first');
        return;
    }

    try {
        Utils.showLoading('Analyzing gaps for optimization...');
        const targetContext = typeof collectTargetJobContext === 'function' ? collectTargetJobContext() : null;
        await apiClient.syncTargetJobContext(targetContext);

        let gaps = [];
        let questions = [];
        try {
            const gapResponse = await apiClient.runGapAnalysis();
            gaps = gapResponse.gaps || [];
            questions = gapResponse.questions_to_ask || [];
            if (gaps.length) displayGapAnalysis(gaps);
        } catch (_) {
            /* gap analysis optional for re-optimize */
        }
        Utils.hideLoading();

        const optimizationResult = await showOptimizationDialog({ gaps, questions });
        if (!optimizationResult?.proceed) return;

        const answered = (optimizationResult.answers || []).filter((a) => a.answer);
        if (answered.length) {
            Utils.showLoading('Applying your clarifications...');
            await apiClient.submitOptimizationClarifications(answered);
        }

        Utils.showLoading('Optimizing resume for one A4 page...');
        const response = await apiClient.optimizeResume(
            'Optimize my resume for the target job. Shorten wording and spacing so the entire resume fits on one A4 page without losing key achievements.',
            targetContext
        );

        if (response.resume_html && response.resume_html.html) {
            displayResume(response.resume_html.html);
        } else {
            const resumeData = await apiClient.getResumeHtml();
            if (resumeData.resume_html && resumeData.resume_html.html) {
                displayResume(resumeData.resume_html.html);
            }
        }
        updateResumeLanguageBadge(response.resume_content_json?.meta?.language || currentResumeLanguage);
        Utils.hideLoading();
        Utils.showToast('Resume optimized for one A4 page');
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast('Optimization failed: ' + error.message);
        console.error('Optimization error:', error);
    }
}

/**
 * Update agent status indicator
 */
function updateAgentStatus(agentId, status) {
    const agentElement = document.getElementById(agentId);
    if (!agentElement) return;

    const statusIcon = agentElement.querySelector('.status-icon');
    const iconMap = {
        'pending': '<i class="fas fa-clock"></i>',
        'running': '<i class="fas fa-circle-notch fa-spin"></i>',
        'completed': '<i class="fas fa-check-circle text-green-400"></i>',
        'failed': '<i class="fas fa-times-circle text-red-400"></i>',
    };

    if (statusIcon) {
        statusIcon.innerHTML = iconMap[status] || iconMap['pending'];
    }
}

/**
 * Update step indicator
 */
function updateStepIndicator(stepNumber, status) {
    const stepElement = document.getElementById(`step-${stepNumber}`);
    if (!stepElement) return;

    stepElement.classList.remove('active', 'completed');
    stepElement.classList.add(status);
}

/**
 * Download resume as HTML
 */
async function downloadResume(format = 'html') {
    try {
        if (format === 'html') {
            const resumeData = await apiClient.getResumeHtml();
            if (resumeData.resume_html && resumeData.resume_html.html) {
                const blob = new Blob([resumeData.resume_html.html], { type: 'text/html' });
                Utils.downloadFile(blob, 'resume.html');
                Utils.showToast('Resume downloaded');
            }
        }
    } catch (error) {
        Utils.showToast('Download failed: ' + error.message);
        console.error('Download error:', error);
    }
}

/**
 * Export resume as PDF
 */
async function exportResume(format = 'pdf') {
    try {
        Utils.showLoading('Exporting resume...');

        let blob;
        if (format === 'pdf') {
            blob = await apiClient.exportResumePDF();
            Utils.downloadFile(blob, 'resume.pdf');
        } else if (format === 'docx') {
            blob = await apiClient.exportResumeDOCX();
            Utils.downloadFile(blob, 'resume.docx');
        }

        Utils.hideLoading();
        Utils.showToast('Resume exported successfully');
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast('Export failed: ' + error.message);
        console.error('Export error:', error);
    }
}
