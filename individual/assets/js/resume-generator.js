async function restoreDraftOnLoad() {
    try {
        const recordId = typeof SavedProfileBootstrap !== 'undefined'
            ? SavedProfileBootstrap.getRecordIdFromUrl()
            : '';
        if (recordId && typeof apiClient !== 'undefined' && apiClient.isLoggedIn()) {
            await ProfileEditor.restoreSavedRecord(recordId);
            return;
        }
        const restored = await ProfileEditor.loadFromServer();
        if (restored) {
            showUploadResultsPanel();
            if (typeof refreshLanguageChecklist === 'function') {
                await refreshLanguageChecklist(currentResumeLanguage);
            }
            const validation = typeof refreshAndValidateRequiredFields === 'function'
                ? await refreshAndValidateRequiredFields()
                : { valid: true };
            if (validation.valid) {
                revealJdSection();
            } else if (typeof updateProfileContinueUi === 'function') {
                updateProfileContinueUi(validation.checklist);
            }
            updateUploadContinueButton();
        }
    } catch (_) {
        /* no draft yet */
    }
}

