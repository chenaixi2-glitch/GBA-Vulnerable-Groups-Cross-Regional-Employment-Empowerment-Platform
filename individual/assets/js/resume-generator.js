function updateResumeViewSwitcher() {
    const switcher = document.getElementById('resume-view-switcher');
    const editBtn = document.getElementById('btn-view-edit');
    const previewBtn = document.getElementById('btn-view-preview');
    const hint = document.getElementById('resume-view-switcher-hint');
    if (!switcher) return;

    const showSwitcher = hasResumeProfileData();
    switcher.classList.toggle('hidden', !showSwitcher);

    if (editBtn) {
        editBtn.classList.toggle('active', currentResumeView === 'edit');
        editBtn.setAttribute('aria-selected', currentResumeView === 'edit' ? 'true' : 'false');
    }
    if (previewBtn) {
        previewBtn.disabled = !resumeGenerated;
        previewBtn.classList.toggle('active', currentResumeView === 'preview');
        previewBtn.setAttribute('aria-selected', currentResumeView === 'preview' ? 'true' : 'false');
        previewBtn.setAttribute('aria-disabled', resumeGenerated ? 'false' : 'true');
    }
    if (hint) {
        hint.classList.toggle('hidden', !resumeGenerated);
    }
}

function setResumeView(mode, options = {}) {
    const { scroll = false } = options;
    if (mode === 'preview' && !resumeGenerated) {
        Utils.showToast(uiT('resume.toast.generateFirst', 'Please generate a resume first'));
        return;
    }

    currentResumeView = mode;
    const editSection = document.getElementById('profile-editor-section');
    const previewSection = document.getElementById('resume-preview-section');

    if (mode === 'edit') {
        editSection?.classList.remove('hidden');
        previewSection?.classList.add('hidden');
    } else {
        previewSection?.classList.remove('hidden');
        editSection?.classList.add('hidden');
    }

    updateResumeViewSwitcher();
    if (typeof updateProfileContinueUi === 'function') {
        updateProfileContinueUi(typeof lastChecklistData !== 'undefined' ? lastChecklistData : null);
    }

    if (scroll) {
        const target = mode === 'edit' ? editSection : previewSection;
        target?.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
}

function switchResumeView(mode) {
    if (mode === currentResumeView) {
        const target = mode === 'edit'
            ? document.getElementById('profile-editor-section')
            : document.getElementById('resume-preview-section');
        target?.scrollIntoView({ behavior: 'smooth', block: 'start' });
        return;
    }

    if (mode === 'edit' && typeof ProfileEditor !== 'undefined' && ProfileEditor.collectDraftFromForm) {
        ProfileEditor.draft = ProfileEditor.collectDraftFromForm();
    }

    setResumeView(mode, { scroll: true });
}

