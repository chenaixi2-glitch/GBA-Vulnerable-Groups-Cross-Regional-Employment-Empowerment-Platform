function applyResumeGenerationResult(response, lang, options = {}) {
    const {
        beforeDraftSnapshot = null,
        deferPreview = false,
        polishingFactIds = [],
        silent = false,
        highlightTranslations = false,
    } = options;

    if (!deferPreview && response?.resume_html?.html) {
        displayResume(response.resume_html.html);
    }

    updateResumeLanguageBadge(response?.language || lang);
    if (response?.language_checklist) {
        renderLanguageChecklistPanel(response.language_checklist);
    } else if (typeof refreshLanguageChecklist === 'function') {
        refreshLanguageChecklist(lang);
    }
    resumeGenerated = true;
    updateResumeViewSwitcher();
    updateProfileExportUi();

    if (deferPreview) {
        document.getElementById('resume-preview-section')?.classList.add('hidden');
    } else {
        document.getElementById('resume-preview-section')?.classList.remove('hidden');
        showResumeChatPanel();
    }

    if (response?.resume_content_json
        && typeof ProfileEditor !== 'undefined'
        && ProfileEditor.syncDraftFromResumeContent) {
        const changed = ProfileEditor.syncDraftFromResumeContent(response.resume_content_json, {
            beforeSnapshot: beforeDraftSnapshot,
            polishingFactIds,
            highlightTranslations,
        });
        if (changed > 0 && !deferPreview && !silent) {
            setResumeView('edit', { scroll: false });
            Utils.showToast(uiT(
                'resume.toast.translationReviewFields',
                '{count} title-level field(s) highlighted (name, school, company/project) — please review',
                { count: changed }
            ));
        } else if (deferPreview) {
            setResumeView('edit', { scroll: true, scrollTargetId: 'profile-editor-body' });
        }
    } else if (deferPreview) {
        setResumeView('edit', { scroll: true, scrollTargetId: 'profile-editor-body' });
    }
}

/**
 * Generate resume from parsed profile only — no JD or gap optimization.
 */
async function generateResumeFromProfile(options = {}) {
    const { silent = false, language } = options;

    if (!hasParsedProfileOnPage()) {
        Utils.showToast(uiT('resume.toast.uploadOrPaste', 'Please upload a file or paste resume text'));
        document.getElementById('upload-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
        return false;
    }

    const lang = typeof normalizeResumeLang === 'function'
        ? normalizeResumeLang(language || currentResumeLanguage)
        : (language || currentResumeLanguage || 'zh');

    if (resumeGenerated && lang === normalizeResumeLang(currentResumeLanguage)) {
        setResumeView('edit', { scroll: true });
        return true;
    }

    if (resumeGenerated) {
        await translateResume(lang);
        return true;
    }

    if (!guardAiTaskRetry()) return false;

    try {
        beginAiTaskAttempt();
        if (!silent) {
            Utils.showLoading(uiT('resume.toast.generatingProfileResume', 'Generating resume from your profile — usually about 2–3 minutes…'));
        }
        const beforeDraftSnapshot = (typeof ProfileEditor !== 'undefined' && ProfileEditor.captureDraftSnapshot)
            ? ProfileEditor.captureDraftSnapshot()
            : null;

        if (typeof refreshAndValidateRequiredFields === 'function') {
            const { valid, required } = await refreshAndValidateRequiredFields();
            if (!valid && required.length) {
                if (!silent) Utils.hideLoading();
                const labels = required.slice(0, 5).map((item) => item.label).join(', ');
                Utils.showToast(uiT('resume.toast.requiredFieldsMissing', 'Please complete required fields first: {labels}', { labels }));
                if (typeof scrollToChecklistField === 'function') {
                    scrollToChecklistField(required[0]);
                }
                return false;
            }
        }

        const { draft, lang: targetLang } = await prepareEditorDraftForAiTask(lang);
        const response = await apiClient.generateResumeFromProfile(targetLang, draft);
        applyResumeGenerationResult(response, targetLang, { beforeDraftSnapshot, deferPreview: true });
        resetResumeUndoHistory();
        if (!silent) {
            Utils.hideLoading();
            Utils.showToast(uiT(
                'resume.toast.generatedEditBeforeExport',
                'Resume content ready in the editor — review and export when ready (preview renders on export)'
            ));
        }
        setResumeView('edit', { scroll: !silent, scrollTargetId: silent ? null : 'profile-editor-body' });
        return true;
    } catch (error) {
        if (!silent) Utils.hideLoading();
        Utils.showAiTaskErrorToast(error, 'resume.toast.profileResumeFailed', 'Could not generate resume: {msg}', { msg: error.message });
        console.error('Profile resume generation error:', error);
        return false;
    }
}

