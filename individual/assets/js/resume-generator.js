const GAP_TYPE_I18N = {
    missing_skill: ['resume.toast.gapTypeMissingSkill', 'Missing skill'],
    missing_experience: ['resume.toast.gapTypeMissingExperience', 'Missing experience'],
    no_quantification: ['resume.toast.gapTypeNoQuantification', 'Lack of quantification'],
    low_relevance: ['resume.toast.gapTypeLowRelevance', 'Low relevance'],
    experience_gap: ['resume.toast.gapTypeExperienceGap', 'Experience gap'],
    skill_gap: ['resume.toast.gapTypeSkillGap', 'Skill gap'],
};

const GAP_SEVERITY_I18N = {
    critical: ['resume.toast.severityCritical', 'Critical'],
    high: ['resume.toast.severityHigh', 'High'],
    medium: ['resume.toast.severityMedium', 'Medium'],
    low: ['resume.toast.severityLow', 'Low'],
};

function formatGapTypeLabel(type) {
    if (!type) return '';
    const entry = GAP_TYPE_I18N[String(type).toLowerCase()];
    if (entry) return uiT(entry[0], entry[1]);
    return String(type).replace(/_/g, ' ');
}

function formatGapSeverityLevel(severity) {
    const key = String(severity || 'medium').toLowerCase();
    const entry = GAP_SEVERITY_I18N[key] || GAP_SEVERITY_I18N.medium;
    return uiT(entry[0], entry[1]);
}

function formatGapSeverityBadge(severity) {
    return uiT(
        'resume.toast.severityBadge',
        '{level} priority',
        { level: formatGapSeverityLevel(severity) }
    );
}

function escapeGapHtml(str) {
    if (!str) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;');
}

/**
 * Display gap analysis results
 */
function displayGapAnalysis(gaps) {
    const container = document.getElementById('gap-analysis-content');
    lastGapAnalysisData = gaps && gaps.length ? gaps : null;

    if (!gaps || gaps.length === 0) {
        container.innerHTML = '<p class="text-gray-600">' + uiT('resume.toast.noGaps', 'No significant skill gaps detected!') + '</p>';
        return;
    }

    const html = gaps.map(gap => `
        <div class="gap-analysis-card">
            <div class="flex items-start justify-between mb-2">
                <div>
                    <h4 class="font-bold text-gray-900">${escapeGapHtml(gap.skill || gap.description)}</h4>
                    <p class="text-sm text-gray-600 mt-1">${escapeGapHtml(gap.suggestion || uiT('resume.toast.considerSkill', 'Consider developing this skill'))}</p>
                </div>
                <span class="px-3 py-1 rounded-full text-xs font-medium ${getSeverityClass(gap.severity)}">
                    ${formatGapSeverityBadge(gap.severity)}
                </span>
            </div>
            ${gap.type ? `<div class="text-xs text-gray-500">${uiT('resume.toast.gapType', 'Type: {type}', { type: formatGapTypeLabel(gap.type) })}</div>` : ''}
        </div>
    `).join('');

    container.innerHTML = html;
}

/**
 * Get CSS class based on severity
 */
function getSeverityClass(severity) {
    switch (severity?.toLowerCase()) {
        case 'high':
        case 'critical':
            return 'bg-red-100 text-red-800';
        case 'medium':
            return 'bg-yellow-100 text-yellow-800';
        case 'low':
            return 'bg-green-100 text-green-800';
        default:
            return 'bg-gray-100 text-gray-800';
    }
}

