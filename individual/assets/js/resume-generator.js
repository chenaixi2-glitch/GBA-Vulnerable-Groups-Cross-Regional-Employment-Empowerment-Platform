async function captureCurrentResumeSnapshot() {
    const preview = document.getElementById('resume-preview');
    const snapshot = {
        html: preview?.innerHTML || '',
        language: currentResumeLanguage,
        resume_content_json: null,
        render_config: null,
        resume_html: null,
    };

    if (!snapshot.html) {
        return snapshot;
    }

    snapshot.resume_html = { html: snapshot.html, version: 1 };

    try {
        const [contentResp, htmlResp] = await Promise.all([
            apiClient.getResumeContent().catch(() => null),
            apiClient.getResumeHtml().catch(() => null),
        ]);
        if (contentResp?.resume_content_json) {
            snapshot.resume_content_json = contentResp.resume_content_json;
            snapshot.language = contentResp.resume_content_json.meta?.language || snapshot.language;
        }
        if (htmlResp?.resume_html) {
            snapshot.resume_html = htmlResp.resume_html;
            if (htmlResp.resume_html.html) {
                snapshot.html = htmlResp.resume_html.html;
            }
        }
    } catch (_) {
        /* offline / mock — preview HTML is enough for undo display */
    }

    return snapshot;
}

function resetResumeUndoHistory() {
    resumeUndoStack = [];
    resumeRedoStack = [];
    updateResumeUndoRedoUi();
}

function pushResumeUndoSnapshot(snapshot) {
    if (!snapshot?.html) return;
    resumeUndoStack.push(snapshot);
    if (resumeUndoStack.length > RESUME_UNDO_MAX) {
        resumeUndoStack.shift();
    }
    resumeRedoStack = [];
    updateResumeUndoRedoUi();
}

function updateResumeUndoRedoUi() {
    const undoBtn = document.getElementById('resume-chat-undo');
    const redoBtn = document.getElementById('resume-chat-redo');
    const canUndo = resumeUndoStack.length > 0;
    const canRedo = resumeRedoStack.length > 0;

    if (undoBtn) {
        undoBtn.disabled = !canUndo || resumeChatBusy;
        undoBtn.setAttribute('aria-disabled', canUndo && !resumeChatBusy ? 'false' : 'true');
    }
    if (redoBtn) {
        redoBtn.disabled = !canRedo || resumeChatBusy;
        redoBtn.setAttribute('aria-disabled', canRedo && !resumeChatBusy ? 'false' : 'true');
    }
}

async function applyResumeSnapshot(snapshot) {
    if (!snapshot?.html) {
        throw new Error(uiT('resume.toast.undoUnavailable', 'Nothing to restore'));
    }

    const restored = await apiClient.restoreResumeSnapshot(snapshot);
    const html = restored?.resume_html?.html || snapshot.html;
    displayResume(html);
    updateResumeLanguageBadge(restored?.language || snapshot.language || currentResumeLanguage);

    if (typeof refreshLanguageChecklist === 'function') {
        await refreshLanguageChecklist(currentResumeLanguage);
    }

    return restored;
}

async function undoResumeEdit() {
    if (!resumeGenerated || resumeChatBusy || resumeUndoStack.length === 0) {
        return;
    }

    setResumeChatBusy(true);
    try {
        const current = await captureCurrentResumeSnapshot();
        const previous = resumeUndoStack.pop();
        resumeRedoStack.push(current);
        await applyResumeSnapshot(previous);
        appendResumeChatMessage('assistant', uiT('resume.chat.undone', 'Undid the last change. Preview restored.'));
        Utils.showToast(uiT('resume.toast.undone', 'Last change undone'));
    } catch (error) {
        Utils.showToast(uiT('resume.toast.undoFailed', 'Undo failed: {msg}', { msg: error.message }));
        console.error('Resume undo error:', error);
    } finally {
        setResumeChatBusy(false);
        updateResumeUndoRedoUi();
    }
}

async function redoResumeEdit() {
    if (!resumeGenerated || resumeChatBusy || resumeRedoStack.length === 0) {
        return;
    }

    setResumeChatBusy(true);
    try {
        const current = await captureCurrentResumeSnapshot();
        const next = resumeRedoStack.pop();
        resumeUndoStack.push(current);
        await applyResumeSnapshot(next);
        appendResumeChatMessage('assistant', uiT('resume.chat.redone', 'Redid the change. Preview updated.'));
        Utils.showToast(uiT('resume.toast.redone', 'Change restored'));
    } catch (error) {
        Utils.showToast(uiT('resume.toast.redoFailed', 'Redo failed: {msg}', { msg: error.message }));
        console.error('Resume redo error:', error);
    } finally {
        setResumeChatBusy(false);
        updateResumeUndoRedoUi();
    }
}

function escapeResumeChatHtml(text) {
    const div = document.createElement('div');
    div.textContent = text || '';
    return div.innerHTML;
}

function formatResumeChatReply(response) {
    if (response?.resume_html?.html) {
        return uiT('resume.chat.updated', 'Resume updated based on your request. Check the preview on the left.');
    }
    const reply = (response?.reply_message || '').trim();
    if (!reply) {
        return uiT('resume.chat.processed', 'Request processed.');
    }
    const finalMatch = reply.match(/\*\*最终结果\*\*\s*\n([\s\S]*)/);
    if (finalMatch) {
        return finalMatch[1].trim();
    }
    const enFinalMatch = reply.match(/\*\*Final result\*\*\s*\n([\s\S]*)/i);
    if (enFinalMatch) {
        return enFinalMatch[1].trim();
    }
    if (reply.length > 600) {
        const lines = reply.split('\n').filter((line) => line.trim());
        return lines.slice(-4).join('\n').trim();
    }
    return reply;
}

function appendResumeChatMessage(role, content) {
    const container = document.getElementById('resume-chat-messages');
    if (!container) return;

    const wrap = document.createElement('div');
    wrap.className = role === 'user' ? 'flex justify-end' : 'flex justify-start';

    const bubble = document.createElement('div');
    bubble.className = `resume-chat-bubble ${role} px-3 py-2 text-sm leading-relaxed whitespace-pre-wrap`;
    bubble.innerHTML = escapeResumeChatHtml(content).replace(/\n/g, '<br>');
    wrap.appendChild(bubble);
    container.appendChild(wrap);
    container.scrollTop = container.scrollHeight;
}

