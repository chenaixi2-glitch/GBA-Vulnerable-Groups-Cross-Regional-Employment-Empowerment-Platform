function hasParsedProfileOnPage() {
    if (typeof ProfileEditor === 'undefined' || !ProfileEditor.collectDraftFromForm) {
        return false;
    }
    const draft = ProfileEditor.draft || ProfileEditor.collectDraftFromForm();
    if (typeof ProfileEditor.isDraftEmpty === 'function') {
        return !ProfileEditor.isDraftEmpty(draft);
    }
    return Boolean(draft?.profile_basic?.name || (draft?.modules || []).length);
}

/**
 * Sync profile editor → backend session, apply target resume language, return fresh draft.
 */
async function prepareEditorDraftForAiTask(language) {
    const lang = typeof normalizeResumeLang === 'function'
        ? normalizeResumeLang(language || currentResumeLanguage || 'zh')
        : (language || currentResumeLanguage || 'zh');

    currentResumeLanguage = lang;
    if (typeof updateResumeLanguageBadge === 'function') {
        updateResumeLanguageBadge(lang);
    }
    if (typeof ProfileEditor !== 'undefined' && ProfileEditor.updatePhotoVisibility) {
        ProfileEditor.updatePhotoVisibility(lang);
    }
    if (typeof syncResumeLanguageButtons === 'function') {
        syncResumeLanguageButtons();
    }

    await syncDraftBeforeGenerate({ required: true, showLoading: false });

    const draft = (typeof ProfileEditor !== 'undefined' && ProfileEditor.collectDraftFromForm)
        ? ProfileEditor.collectDraftFromForm()
        : null;
    if (typeof ProfileEditor !== 'undefined' && draft) {
        ProfileEditor.draft = draft;
    }

    apiClient.ensureSessionStarted();
    try {
        await apiClient.setResumeLanguage(lang);
    } catch (error) {
        console.warn('Resume language sync before AI task failed:', error.message);
    }

    return { draft, lang };
}

/**
 * Push editor draft to backend session so generate works after page restore (no re-upload).
 */
async function syncDraftBeforeGenerate(options = {}) {
    const { required = false, showLoading = false } = options;
    if (typeof ProfileEditor === 'undefined' || !ProfileEditor.collectDraftFromForm) {
        if (required) {
            throw new Error(uiT('resume.toast.uploadOrPaste', 'Please upload a file or paste resume text'));
        }
        return false;
    }

    let draft = ProfileEditor.collectDraftFromForm();
    if (typeof ProfileEditor.isDraftEmpty === 'function' && ProfileEditor.isDraftEmpty(draft)
        && ProfileEditor.draft && !ProfileEditor.isDraftEmpty(ProfileEditor.draft)) {
        draft = ProfileEditor.draft;
    }
    ProfileEditor.draft = draft;

    if (typeof ProfileEditor.isDraftEmpty === 'function' && ProfileEditor.isDraftEmpty(draft)) {
        if (required) {
            throw new Error(uiT('resume.toast.uploadOrPaste', 'Please upload a file or paste resume text'));
        }
        return false;
    }

    try {
        if (showLoading) {
            Utils.showLoading(uiT('resume.toast.syncingProfile', 'Syncing your profile before generation...'));
        }
        apiClient.ensureSessionStarted();
        await apiClient.saveResumeDraft(draft);
        return true;
    } catch (error) {
        console.warn('Draft sync failed:', error.message);
        if (required) {
            throw new Error(uiT('resume.toast.syncProfileFailed', 'Could not sync profile to server: {msg}. Try Analyze Resume again.', { msg: error.message }));
        }
        return false;
    } finally {
        if (showLoading) {
            Utils.hideLoading();
        }
    }
}

