async function submitResumeChatEdit() {
    if (!resumeGenerated) {
        Utils.showToast(uiT('resume.toast.generateFirst', 'Please generate a resume first'));
        return;
    }
    if (resumeChatBusy) return;

    const input = document.getElementById('resume-chat-input');
    const message = input?.value.trim();
    if (!message) {
        Utils.showToast(uiT('resume.toast.chatEmpty', 'Please enter your edit request'));
        return;
    }

    appendResumeChatMessage('user', message);
    if (input) input.value = '';
    setResumeChatBusy(true);
    appendResumeChatMessage('assistant', uiT('resume.chat.thinking', 'Working on your changes…'));

    try {
        const beforeSnapshot = await captureCurrentResumeSnapshot();
        const targetContext = typeof collectTargetJobContext === 'function' ? collectTargetJobContext() : null;
        await apiClient.syncTargetJobContext(targetContext);
        await apiClient.syncResumeLanguageToSession();

        const response = await apiClient.chat(message, [], {
            language: currentResumeLanguage,
            usePageLanguage: false,
            allowMockFallback: true,
        });

        const messages = document.getElementById('resume-chat-messages');
        if (messages?.lastChild) {
            messages.removeChild(messages.lastChild);
        }

        const changed = Boolean(
            response.resume_html?.html
            || response.triggered_agents?.includes('render_agent')
            || response.triggered_agents?.includes('content_agent')
        );

        if (response.resume_html?.html) {
            displayResume(response.resume_html.html);
            updateResumeLanguageBadge(response.resume_content_json?.meta?.language || currentResumeLanguage);
        } else if (response.triggered_agents?.includes('render_agent')) {
            const resumeData = await apiClient.getResumeHtml();
            if (resumeData.resume_html?.html) {
                displayResume(resumeData.resume_html.html);
            }
        }

        if (changed && beforeSnapshot.html) {
            pushResumeUndoSnapshot(beforeSnapshot);
        }

        appendResumeChatMessage('assistant', formatResumeChatReply(response));

        if (response.resume_html?.html) {
            Utils.showToast(uiT('resume.toast.chatUpdated', 'Resume updated'));
        }
    } catch (error) {
        const messages = document.getElementById('resume-chat-messages');
        if (messages?.lastChild) {
            messages.removeChild(messages.lastChild);
        }
        appendResumeChatMessage(
            'assistant',
            uiT('resume.toast.chatFailed', 'Edit failed: {msg}', { msg: error.message })
        );
        Utils.showToast(uiT('resume.toast.chatFailed', 'Edit failed: {msg}', { msg: error.message }));
        console.error('Resume chat edit error:', error);
    } finally {
        setResumeChatBusy(false);
    }
}

/**
 * Update language badge and toggle button states
 */
function updateResumeLanguageBadge(language) {
    currentResumeLanguage = typeof normalizeResumeLang === 'function'
        ? normalizeResumeLang(language)
        : (String(language || 'zh').toLowerCase().startsWith('en') ? 'en' : 'zh');
    const badge = document.getElementById('resume-language-badge');
    const a4Badge = document.getElementById('resume-a4-badge');

    if (badge) {
        badge.dataset.activeLang = currentResumeLanguage;
        badge.textContent = typeof resumeLangDisplayLabel === 'function'
            ? resumeLangDisplayLabel(currentResumeLanguage)
            : currentResumeLanguage;
        const isWestern = currentResumeLanguage === 'en' || currentResumeLanguage === 'pt';
        badge.className = isWestern
            ? 'px-2 py-0.5 rounded text-xs font-medium bg-blue-100 text-blue-800'
            : 'px-2 py-0.5 rounded text-xs font-medium bg-red-100 text-red-800';
    }
    if (a4Badge) {
        a4Badge.classList.remove('hidden');
    }
    if (typeof syncResumeLanguageButtons === 'function') {
        syncResumeLanguageButtons();
    }

    if (resumeGenerated && typeof refreshLanguageChecklist === 'function') {
        refreshLanguageChecklist(currentResumeLanguage);
    }

    if (lastGapAnalysisData && lastGapAnalysisData.length) {
        if (typeof apiClient !== 'undefined' && apiClient.useMockMode && apiClient.mockService) {
            lastGapAnalysisData = apiClient.mockService.buildMockGaps(currentResumeLanguage);
        }
        displayGapAnalysis(lastGapAnalysisData);
    }
}

