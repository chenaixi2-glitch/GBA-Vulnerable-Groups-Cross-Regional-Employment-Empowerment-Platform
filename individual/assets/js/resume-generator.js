/**
 * Generate JD-tailored resume (optional Step 2 — gap analysis + optimization).
 */
async function generateResume() {
    const generateBtn = document.getElementById('btn-generate');
    if (generateBtn?.dataset.busy === '1') return;

    const setGenerateBusy = (busy) => {
        if (!generateBtn) return;
        generateBtn.dataset.busy = busy ? '1' : '0';
        generateBtn.disabled = busy;
        generateBtn.classList.toggle('opacity-50', busy);
        generateBtn.classList.toggle('cursor-not-allowed', busy);
    };

    setGenerateBusy(true);
    try {
        apiClient.ensureSessionStarted();

        if (!hasParsedProfileOnPage()) {
            Utils.showToast(uiT('resume.toast.uploadOrPaste', 'Please upload a file or paste resume text'));
            document.getElementById('upload-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
            return;
        }

        if (typeof refreshAndValidateRequiredFields === 'function') {
            Utils.showLoading(uiT('resume.toast.validatingProfile', 'Checking required profile fields...'));
            const { valid, required } = await refreshAndValidateRequiredFields();
            Utils.hideLoading();
            if (!valid && required.length) {
                const labels = required.slice(0, 5).map((item) => item.label).join(', ');
                Utils.showToast(uiT('resume.toast.requiredFieldsMissing', 'Please complete required fields first: {labels}', { labels }));
                if (typeof scrollToChecklistField === 'function') {
                    scrollToChecklistField(required[0]);
                }
                document.getElementById('profile-editor-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
                return;
            }
        }

        const jdTextarea = document.getElementById('jd-text');
        const industrySelect = document.getElementById('industry-select');
        const experienceSelect = document.getElementById('experience-level');
        if (!jdTextarea || !industrySelect || !experienceSelect) {
            throw new Error(uiT('errors.pageSetupIncomplete', 'Page setup incomplete — please refresh and try again'));
        }

        let jdText = jdTextarea.value.trim();
        const industry = industrySelect.value;
        const experienceLevel = experienceSelect.value;
        const employerType = document.getElementById('employer-type-select')?.value || '';

        if (!jdText) {
            if (!industry || !experienceLevel || !employerType) {
                Utils.showToast(uiT('resume.toast.pasteOrSelectJd', 'Paste a job description, or select industry, employer type, and experience level to generate one'));
                return;
            }
            await fillSuggestedJd(industry, experienceLevel, employerType, { silent: false });
            jdText = jdTextarea.value.trim();
            if (!jdText) {
                Utils.showToast(uiT('resume.toast.jdGenerateRetry', 'Could not generate job description. Please try again or paste one manually'));
                return;
            }
        }

        // 岗位名 / 自动生成 JD 须用户确认后再进入优化
        let jdAlignmentHint = '';
        const confirmResult = await ensureJdConfirmedBeforeProceed(jdText, {
            jdAutoGenerated,
            jdUserConfirmed,
        });
        if (!confirmResult?.confirmed) {
            Utils.showToast(uiT('resume.toast.cancelledConfirmJd', 'Cancelled — please confirm the job description before generating the resume'));
            return;
        }
        jdText = confirmResult.jd_text || jdTextarea.value.trim();
        jdUserConfirmed = true;
        jdAutoGenerated = false;
        jdAlignmentHint = confirmResult.clarification_hint || confirmResult.alignment_note || '';

        await syncDraftBeforeGenerate({ required: true, showLoading: true });

        Utils.showLoading(uiT('resume.toast.analyzingJd', 'Analyzing job description...'));
        document.getElementById('agent-status-panel').classList.remove('hidden');
        document.getElementById('empty-state').classList.add('hidden');

        updateStepIndicator(2, 'completed');
        updateStepIndicator(3, 'active');

        updateAgentStatus('agent-profile', 'completed');
        updateAgentStatus('agent-jd', 'running');

        const targetContext = typeof collectTargetJobContext === 'function' ? collectTargetJobContext() : null;

        await apiClient.submitJobDescription(jdText, targetContext);

        updateAgentStatus('agent-jd', 'completed');
        updateAgentStatus('agent-gap', 'running');

        // 单独以页面 UI 语言跑缺口分析，避免 JD 提交链路返回旧语言/缓存的 questions
        let gapGaps = [];
        let gapQuestions = [];
        let gapRemovals = [];
        try {
            const gapResponse = await apiClient.runGapAnalysis();
            gapGaps = gapResponse.gaps || [];
            gapQuestions = gapResponse.questions_to_ask || [];
            gapRemovals = gapResponse.experiences_to_remove || [];
            if (gapGaps.length) displayGapAnalysis(gapGaps);
        } catch (_) {
            /* gap analysis optional */
        }

        updateAgentStatus('agent-gap', 'completed');
        Utils.hideLoading();

        // 交互式追问：技术栈/经历不明确时向用户提问；删除经历须说明原因
        const optimizationResult = await showOptimizationDialog({
            gaps: gapGaps,
            questions: gapQuestions,
            removals: gapRemovals,
            alignmentHint: jdAlignmentHint,
        });
        if (!optimizationResult?.proceed) {
            Utils.showToast(uiT('resume.toast.cancelledGenerate', 'Resume generation cancelled'));
            return;
        }

        const answered = (optimizationResult.answers || []).filter((a) => a.answer);
        const agreedRemovals = (optimizationResult.removals || []).filter((r) => r.agreed);
        if (answered.length || agreedRemovals.length) {
            Utils.showLoading(uiT('resume.toast.updatingProfile', 'Updating profile with your answers...'));
            await apiClient.submitOptimizationFeedback({
                answers: answered,
                removals: agreedRemovals,
            });
            Utils.hideLoading();
        }

        updateAgentStatus('agent-content', 'running');
        Utils.showLoading(uiT('resume.toast.generatingResume', 'Generating your customized resume...'));

        const resumeResponse = await apiClient.generateResume(
            'Please generate a customized resume based on my experience and target position. Polish each experience entry to align with the target job, add quantified results only when supported by my profile facts, follow industry-standard resume conventions, and never fabricate numbers or achievements. Keep all content within one A4 page.',
            targetContext
        );

        updateAgentStatus('agent-content', 'completed');
        updateAgentStatus('agent-render', 'running');

        if (resumeResponse.resume_html && resumeResponse.resume_html.html) {
            applyResumeGenerationResult(resumeResponse, resumeResponse.resume_content_json?.meta?.language || currentResumeLanguage);
        } else {
            const resumeData = await apiClient.getResumeHtml();
            if (resumeData.resume_html && resumeData.resume_html.html) {
                applyResumeGenerationResult({ resume_html: resumeData.resume_html }, currentResumeLanguage);
            } else {
                throw new Error(uiT('errors.resumeHtmlUnavailable', 'Resume HTML not available'));
            }
        }

        updateAgentStatus('agent-render', 'completed');
        Utils.hideLoading();

        document.getElementById('gap-analysis-section').classList.remove('hidden');

        updateStepIndicator(3, 'completed');

        resetResumeUndoHistory();

        Utils.showToast(uiT('resume.toast.generated', 'Resume generated successfully!'));

        setResumeView('preview', { scroll: true });

        console.log('Resume generation complete:', resumeResponse);
    } catch (error) {
        Utils.hideLoading();
        Utils.showToast(uiT('resume.toast.generateFailed', 'Failed to generate resume: {msg}', { msg: error.message }));
        console.error('Generation error:', error);

        updateAgentStatus('agent-jd', 'failed');
        updateAgentStatus('agent-gap', 'failed');
        updateAgentStatus('agent-content', 'failed');
        updateAgentStatus('agent-render', 'failed');
    } finally {
        setGenerateBusy(false);
        if (typeof hideOptimizationDialog === 'function') {
            hideOptimizationDialog();
        }
    }
}

