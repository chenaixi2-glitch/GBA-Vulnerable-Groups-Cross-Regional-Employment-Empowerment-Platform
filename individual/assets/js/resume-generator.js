/**
 * Perform resume upload after user confirms overwrite (or when session is empty).
 */
async function executeUploadResume() {
    const resumeText = document.getElementById('resume-text').value.trim();

    if (!currentFile && !resumeText) {
        Utils.showToast(uiT('resume.toast.uploadOrPaste', 'Please upload a file or paste resume text'));
        return;
    }

    if (resumeUploadInProgress) {
        return;
    }
    if (!guardAiTaskRetry()) return;

    const uploadBtn = document.getElementById('btn-upload-resume');
    resumeUploadInProgress = true;
    if (uploadBtn) {
        uploadBtn.disabled = true;
        uploadBtn.setAttribute('aria-disabled', 'true');
    }

    let slowHintTimer = null;
    try {
        beginAiTaskAttempt();
        Utils.showLoading(uiT('resume.toast.uploadingResume', 'Uploading resume...'));
        slowHintTimer = setTimeout(() => {
            Utils.showLoading(uiT('resume.toast.uploadingSlow', 'AI is parsing your resume — usually about 1–2 minutes, please wait…'));
        }, 8000);

        let response;
        
        if (currentFile) {
            response = await apiClient.uploadResume(currentFile);
        } else {
            response = await apiClient.chat(resumeText, [], { replaceProfile: true, usePageLanguage: true });
        }

        if (!response?.candidate_profile) {
            throw new Error(uiT('resume.toast.uploadEmptyResponse', 'No profile data returned. Please try again or paste resume text.'));
        }

        Utils.showLoading(uiT('resume.toast.renderingResults', 'Rendering parsed resume on the right panel...'));

        await ProfileEditor.initFromUpload(response);
        showUploadResultsPanel();

        // AI resume output language follows the uploaded resume language.
        const detectedLang = response?.render_config?.language
            || response?.candidate_profile?.language
            || response?.candidate_profile?.meta?.language;
        if (detectedLang) {
            updateResumeLanguageBadge(detectedLang);
            if (typeof ProfileEditor !== 'undefined' && ProfileEditor.updatePhotoVisibility) {
                ProfileEditor.updatePhotoVisibility(detectedLang);
            }
        }

        // 将解析结果回填到 resume-text 文本框，让用户看到解析后的文本内容
        if (response?.candidate_profile) {
            const profile = response.candidate_profile;
            const lines = [];
            const basic = profile.profile_basic || {};
            if (basic.name) lines.push(parsedFieldLabel('parsedName', 'Name') + ': ' + basic.name);
            if (basic.email) lines.push(parsedFieldLabel('parsedEmail', 'Email') + ': ' + basic.email);
            if (basic.phone) lines.push(parsedFieldLabel('parsedPhone', 'Phone') + ': ' + basic.phone);
            if (basic.city) lines.push(parsedFieldLabel('parsedCity', 'City') + ': ' + basic.city);
            if (profile.facts && profile.facts.length) {
                lines.push('');
                profile.facts.forEach(function(fact) {
                    var title = '';
                    try {
                        var parsed = JSON.parse(fact.content || '{}');
                        title = parsed.title || parsed.name || parsed.company || parsed.school || parsed.skill || '';
                    } catch (_) {
                        title = fact.content ? fact.content.split('\n')[0].slice(0, 80) : '';
                    }
                    var prefix = parsedFactTypeLabel(fact.type);
                    lines.push('[' + prefix + '] ' + (title || fact.content || ''));
                });
            }
            var resumeTextEl = document.getElementById('resume-text');
            if (resumeTextEl) {
                resumeTextEl.value = lines.join('\n');
            }
        }

        resumeGenerated = false;
        jdAutoGenerated = false;
        jdUserConfirmed = false;
        resumeUndoStack = [];
        resumeRedoStack = [];
        updateProfileExportUi();
        document.getElementById('resume-preview-section')?.classList.add('hidden');
        document.getElementById('gap-analysis-section')?.classList.add('hidden');
        if (typeof updateResumeViewSwitcher === 'function') {
            updateResumeViewSwitcher();
        }
        if (typeof currentResumeView !== 'undefined') {
            currentResumeView = 'edit';
        }

        if (typeof refreshLanguageChecklist === 'function') {
            await refreshLanguageChecklist(currentResumeLanguage);
        }

        updateStepIndicator(1, 'active');
        updateUploadContinueButton();
        if (typeof updateProfileContinueUi === 'function') {
            updateProfileContinueUi(typeof lastChecklistData !== 'undefined' ? lastChecklistData : null);
        }
        document.getElementById('profile-editor-section')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
        Utils.hideLoading();
        const requiredCount = typeof getRequiredMissingFromChecklist === 'function' && lastChecklistData
            ? getRequiredMissingFromChecklist(lastChecklistData).length
            : 0;
        Utils.showToast(requiredCount > 0
            ? uiT('resume.toast.analyzedWithRequired', 'Resume analyzed — please complete {count} required field(s) below', { count: requiredCount })
            : uiT('resume.toast.analyzed', 'Resume analyzed successfully'));

        console.log('Profile agent response:', response);
    } catch (error) {
        Utils.hideLoading();
        Utils.showAiTaskErrorToast(error, 'resume.toast.uploadFailed', 'Failed to upload resume: {msg}', { msg: error.message || '' });
        console.error('Upload error:', error);
    } finally {
        resumeUploadInProgress = false;
        updateUploadContinueButton();
        Utils.refreshAiTaskRetryButtonGuards?.();
        if (slowHintTimer) clearTimeout(slowHintTimer);
    }
}

